/**
 * Genera el esquema PostgreSQL (Supabase) a partir del esquema real de MySQL.
 *
 * Se lee el diccionario de datos de la base en uso y no `database/schema.sql`,
 * porque ese volcado ya no refleja lo que hay: le faltan la columna `version`,
 * los índices únicos y las tablas que se añadieron después.
 *
 *   node backend/scripts/migracion/generar-esquema-pg.cjs
 *
 * Escribe database/supabase/01-esquema.sql. No modifica ninguna base de datos.
 */
require('dotenv').config();
const fs = require('fs');
const path = require('path');
const mysql = require('mysql2/promise');

const SALIDA = path.join(__dirname, '../../../database/supabase/01-esquema.sql');

/** Un identificador solo va entre comillas si no es minúsculas simples. */
function id(nombre) {
  return /^[a-z_][a-z0-9_]*$/.test(nombre) ? nombre : `"${nombre}"`;
}

/** Tipo PostgreSQL equivalente al de MySQL. */
function tipoPg(col) {
  const t = col.DATA_TYPE;
  const largo = col.CHARACTER_MAXIMUM_LENGTH;
  switch (t) {
    case 'int': case 'mediumint': return 'integer';
    case 'bigint': return 'bigint';
    case 'smallint': case 'tinyint': return 'smallint';
    case 'decimal': return `numeric(${col.NUMERIC_PRECISION},${col.NUMERIC_SCALE})`;
    case 'double': case 'float': return 'double precision';
    case 'varchar': case 'char': return `varchar(${largo})`;
    case 'text': case 'mediumtext': case 'longtext': case 'tinytext': return 'text';
    case 'date': return 'date';
    // MySQL guarda datetime sin zona horaria; `timestamp` mantiene esa semántica.
    case 'datetime': case 'timestamp': return 'timestamp';
    case 'time': return 'time';
    case 'json': return 'jsonb';
    case 'enum': return `varchar(${largo})`;
    default: throw new Error(`tipo sin equivalencia: ${t} (${col.TABLE_NAME}.${col.COLUMN_NAME})`);
  }
}

/** Valores admitidos de un enum de MySQL, para convertirlo en CHECK. */
function valoresEnum(columnType) {
  const dentro = /^enum\((.*)\)$/i.exec(columnType);
  if (!dentro) return null;
  return dentro[1].split(',').map((v) => v.trim().replace(/^'|'$/g, ''));
}

function defectoPg(col) {
  const d = col.COLUMN_DEFAULT;
  if (d == null) return null;
  if (/^current_timestamp/i.test(d)) return 'now()';
  if (col.DATA_TYPE === 'enum' || /char|text/.test(col.DATA_TYPE)) return `'${d.replace(/^'|'$/g, '')}'`;
  return d;
}

(async () => {
  const c = await mysql.createConnection({
    host: process.env.DB_HOST, user: process.env.DB_USER,
    password: process.env.DB_PASSWORD, database: process.env.DB_NAME,
  });
  const esquema = process.env.DB_NAME;
  const [tablas] = await c.query(
    `SELECT table_name AS tn FROM information_schema.tables
     WHERE table_schema = ? AND table_type = 'BASE TABLE' ORDER BY tn`, [esquema]);

  const partes = [];
  const secuencias = [];
  const conUpdatedAt = [];

  for (const { tn } of tablas) {
    const [cols] = await c.query(
      `SELECT * FROM information_schema.columns WHERE table_schema = ? AND table_name = ?
       ORDER BY ordinal_position`, [esquema, tn]);

    const lineas = [];
    for (const col of cols) {
      const nombre = col.COLUMN_NAME;
      let linea = `  ${id(nombre)} ${tipoPg(col)}`;
      if (/auto_increment/i.test(col.EXTRA ?? '')) {
        linea += ' GENERATED BY DEFAULT AS IDENTITY';
        secuencias.push({ tabla: tn, columna: nombre });
      } else {
        const def = defectoPg(col);
        if (def) linea += ` DEFAULT ${def}`;
      }
      if (col.IS_NULLABLE === 'NO') linea += ' NOT NULL';
      const valores = valoresEnum(col.COLUMN_TYPE);
      if (valores) {
        linea += ` CHECK (${id(nombre)} IN (${valores.map((v) => `'${v}'`).join(', ')}))`;
      }
      lineas.push(linea);
      if (nombre === 'updated_at') conUpdatedAt.push(tn);
    }

    // Clave primaria y restricciones únicas, desde los índices declarados.
    const [idx] = await c.query(
      `SELECT index_name AS ix, non_unique AS nu, seq_in_index AS pos, column_name AS col
       FROM information_schema.statistics WHERE table_schema = ? AND table_name = ?
       ORDER BY ix, pos`, [esquema, tn]);
    const porIndice = new Map();
    for (const r of idx) {
      if (!porIndice.has(r.ix)) porIndice.set(r.ix, { unico: Number(r.nu) === 0, cols: [] });
      porIndice.get(r.ix).cols.push(r.col);
    }
    const indicesSueltos = [];
    for (const [nombre, info] of porIndice) {
      const cols = info.cols.map(id).join(', ');
      if (nombre === 'PRIMARY') lineas.push(`  PRIMARY KEY (${cols})`);
      else if (info.unico) lineas.push(`  CONSTRAINT ${id(nombre)} UNIQUE (${cols})`);
      else indicesSueltos.push(`CREATE INDEX IF NOT EXISTS ${id(tn + '_' + nombre)} ON ${id(tn)} (${cols});`);
    }

    partes.push(`CREATE TABLE IF NOT EXISTS ${id(tn)} (\n${lineas.join(',\n')}\n);`);
    if (indicesSueltos.length) partes.push(indicesSueltos.join('\n'));
  }

  // Las llaves foráneas van al final: así el orden de creación de tablas no importa.
  const [fks] = await c.query(
    `SELECT k.constraint_name AS nombre, k.table_name AS tabla, k.column_name AS col,
            k.referenced_table_name AS reftabla, k.referenced_column_name AS refcol,
            r.delete_rule AS al_borrar
     FROM information_schema.key_column_usage k
     JOIN information_schema.referential_constraints r
       ON r.constraint_schema = k.table_schema AND r.constraint_name = k.constraint_name
     WHERE k.table_schema = ? AND k.referenced_table_name IS NOT NULL
     ORDER BY k.table_name, k.constraint_name`, [esquema]);
  const lineasFk = fks.map((f) =>
    `ALTER TABLE ${id(f.tabla)} ADD CONSTRAINT ${id(f.nombre)} ` +
    `FOREIGN KEY (${id(f.col)}) REFERENCES ${id(f.reftabla)} (${id(f.refcol)})` +
    (f.al_borrar === 'CASCADE' ? ' ON DELETE CASCADE' : '') + ';');

  const cabecera = `-- Esquema de Luciérnaga en PostgreSQL (Supabase).
--
-- Generado por backend/scripts/migracion/generar-esquema-pg.cjs a partir del
-- esquema real de MySQL, no de database/schema.sql, que ya no refleja lo que
-- hay en la base.
--
-- Diferencias respecto a MySQL, todas deliberadas:
--
--   * AUTO_INCREMENT pasa a GENERATED BY DEFAULT AS IDENTITY, que admite que la
--     migración inserte los ids existentes. Al final se recolocan las secuencias.
--   * ON UPDATE CURRENT_TIMESTAMP no existe en PostgreSQL: se sustituye por el
--     trigger \`tocar_updated_at\`, definido abajo una sola vez.
--   * Los enum de MySQL pasan a varchar con un CHECK: un enum de PostgreSQL es
--     un tipo propio y obligaría a migrarlo aparte sin ganar nada aquí.
--   * Las columnas de \`inventario\` van entre comillas porque están en
--     mayúsculas; sin comillas, PostgreSQL las pasaría a minúsculas.
--
-- Idempotente: se puede ejecutar varias veces.

`;

  const triggerUpdated = `
-- Equivalente de ON UPDATE CURRENT_TIMESTAMP.
CREATE OR REPLACE FUNCTION tocar_updated_at() RETURNS trigger AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

${conUpdatedAt.map((t) => `DROP TRIGGER IF EXISTS ${t}_updated_at ON ${id(t)};
CREATE TRIGGER ${t}_updated_at BEFORE UPDATE ON ${id(t)}
  FOR EACH ROW EXECUTE FUNCTION tocar_updated_at();`).join('\n\n')}
`;

  const cuerpo = [cabecera, partes.join('\n\n'), '\n-- Llaves foráneas', lineasFk.join('\n'), triggerUpdated].join('\n');
  fs.mkdirSync(path.dirname(SALIDA), { recursive: true });
  fs.writeFileSync(SALIDA, cuerpo, 'utf8');
  console.log(`esquema escrito en database/supabase/01-esquema.sql (${tablas.length} tablas, ${fks.length} llaves foráneas)`);
  await c.end();
})().catch((e) => { console.error('ERROR:', e.message); process.exit(1); });
